"""Flipper Zero ``.nfc`` (MIFARE Classic 1K, format v4) <-> Proxmark3 ``.eml``.

Shared by every scenario (it used to be duplicated per scenario). Also able to
*generate* a starter badge, used by ``tools/new_scenario.py``.

The .eml format is one hex-encoded block per line (32 hex chars), blocks 0-63,
loaded on the PM3 with ``hf mf eload -f <file.eml>``.
"""

import re
from pathlib import Path
from typing import Dict, Mapping, Optional, Union

PathLike = Union[str, Path]

_BLOCK_RE = re.compile(
    r"^Block\s+(\d+)\s*:\s*([0-9a-fA-F]{2}(?:\s+[0-9a-fA-F]{2}){15})\s*$"
)

#: Transport-configuration access bits (key A/B read+write everything).
DEFAULT_ACCESS = bytes.fromhex("FF078069")
DEFAULT_KEY = bytes.fromhex("FFFFFFFFFFFF")


class NfcConvertError(ValueError):
    """Raised when an .nfc file cannot be parsed or converted."""


def parse_nfc(path: PathLike) -> Dict[int, bytes]:
    """Parse a Flipper v4 MIFARE Classic 1K file -> ``{block: 16 bytes}``."""
    path = Path(path)
    text = path.read_text(encoding="utf-8")
    if "Filetype: Flipper NFC device" not in text:
        raise NfcConvertError(f"{path}: not a Flipper NFC device file")
    if "Device type: MIFARE Classic" not in text:
        raise NfcConvertError(f"{path}: not a MIFARE Classic card")

    blocks: Dict[int, bytes] = {}
    for line in text.splitlines():
        m = _BLOCK_RE.match(line.strip())
        if m:
            blocks[int(m.group(1))] = bytes(int(h, 16) for h in m.group(2).split())
    if len(blocks) != 64:
        raise NfcConvertError(f"{path}: expected 64 blocks, found {len(blocks)}")
    return blocks


def blocks_to_eml(blocks: Mapping[int, bytes]) -> str:
    lines = []
    for i in range(64):
        if i not in blocks:
            raise NfcConvertError(f"Missing block {i}")
        lines.append(blocks[i].hex().upper())
    return "\n".join(lines) + "\n"


def nfc_to_eml(src: PathLike, dst: PathLike) -> None:
    Path(dst).write_text(blocks_to_eml(parse_nfc(src)), encoding="utf-8")


def eml_to_blocks(path: PathLike) -> Dict[int, bytes]:
    path = Path(path)
    lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]
    if len(lines) != 64:
        raise NfcConvertError(f"{path}: expected 64 lines, got {len(lines)}")
    blocks: Dict[int, bytes] = {}
    for i, line in enumerate(lines):
        raw = bytes.fromhex(line)
        if len(raw) != 16:
            raise NfcConvertError(f"{path}: line {i} has {len(raw)} bytes, expected 16")
        blocks[i] = raw
    return blocks


