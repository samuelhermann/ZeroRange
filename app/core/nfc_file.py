# Generation
# ---------------------------------------------------------------------------

def make_mfc1k(uid: bytes, *, keys_a: Optional[Mapping[int, bytes]] = None,
               keys_b: Optional[Mapping[int, bytes]] = None,
               data: Optional[Mapping[int, bytes]] = None) -> Dict[int, bytes]:
    """Build the 64 blocks of a MIFARE Classic 1K card.

    ``keys_a`` / ``keys_b`` map sector -> 6-byte key (default FFFFFFFFFFFF),
    ``data`` maps block -> up to 16 bytes (zero-padded).
    """
    if len(uid) != 4:
        raise ValueError("Only 4-byte UIDs are supported")
    keys_a, keys_b, data = keys_a or {}, keys_b or {}, data or {}
    bcc = uid[0] ^ uid[1] ^ uid[2] ^ uid[3]
    blocks: Dict[int, bytes] = {0: uid + bytes([bcc, 0x08, 0x04, 0x00]) + bytes(8)}
    for sector in range(16):
        trailer = 4 * sector + 3
        blocks[trailer] = (keys_a.get(sector, DEFAULT_KEY) + DEFAULT_ACCESS
                           + keys_b.get(sector, DEFAULT_KEY))
        for blk in range(4 * sector, trailer):
            if blk == 0:
                continue
            payload = bytes(data.get(blk, b""))[:16]
            blocks[blk] = payload.ljust(16, b"\x00")
    return blocks


def render_nfc(blocks: Mapping[int, bytes]) -> str:
    uid = blocks[0][:4]
    lines = [
        "Filetype: Flipper NFC device",
        "Version: 4",
        "# Generated by ZeroRange",
        "Device type: MIFARE Classic",
        f"UID: {uid.hex(' ').upper()}",
        "ATQA: 00 04",
        "SAK: 08",
        "Mifare Classic type: 1K",
        "Data format version: 2",
    ]
    lines += [f"Block {i}: {blocks[i].hex(' ').upper()}" for i in range(64)]
    return "\n".join(lines) + "\n"


def write_nfc(path: PathLike, blocks: Mapping[int, bytes]) -> None:
    Path(path).write_text(render_nfc(blocks), encoding="utf-8")
